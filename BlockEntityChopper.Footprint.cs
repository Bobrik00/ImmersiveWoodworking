/// <summary>
/// T03.02 / T03.06 — the chopper's multiblock SHAPE in one place: the footprint as a single offset table, the
/// orientation maths that turns it into world cells, the mechanical-power input cell (<see cref="InputCellLocal"/> /
/// <see cref="InputFaceFor"/>) and the per-cell collision/selection derived from the SAME table. A direct port of
/// <see cref="BlockEntitySawmill"/>'s Footprint partial. Everything downstream reads the footprint from here — the
/// ghost placement (T03.03), the orientation wiring (T03.04), the teardown drop (T03.05), the power node (E04) and
/// the I/O / chop-point geometry (E05/E06) — so re-shaping the machine (re-scan the Blender model) is a one-table
/// edit, never a hunt for magic offsets.
///
/// FITTED to the authored model (<c>shapes/block/chopper/chopper.json</c>, occupancy scan 2026-07-05): the earlier
/// ~2×3×2 placeholder is replaced by the machine's real mass — a 3×3×4 tower (an axe on a gear-cam over a clamp-bed),
