    // ───────────────────────── The footprint, in the master's LOCAL frame ─────────────────────────
    //
    // Feed/strike axis = +Z (rotated onto the placement facing by RotateToFacing); +X is the perpendicular
    // horizontal; +Y is up. The footprint is FITTED to the authored model (occupancy scan 2026-07-05, see the per-cell
    // %% notes): the machine is a 3×3×4 tower — an OPEN-centre master frame base (0,0,0), where the clamp-bed / log sit
    // (so it is thin posts, not a solid cube) + the two -X/+X arms at Y=0, an X-spine (X=-1,0,+1 at Z=0) rising the full
    // height, a near-full 3-wide head/gear assembly at the top (Y=3), and the thin corner frame posts in between. The
    // scan EXCLUDES the in-model workpiece log (dropmaul-log*, ChopperParts' Hidden group) — it is a Blender reference,
    // not rendered from this model (T07.03 draws the real billet), so it must not add phantom collision. The machine
    // sits ON the ground (model authored at Y≥0), so there is NO -Y "pit"
    // cell: every footprint cell is at/above the master, which is what makes placement STANDARD on flat ground —
    // CanPlaceBlock only needs the cells above/around free (normally air). Index 0 is ALWAYS the master, so callers
    // wanting just the fillers skip [0]. Single source of truth for the shape — see the class summary.
    //
    // FLAT, generated cell list (one line = one collision/selection cell). It is AUTO-DERIVED by scan_collision.py from
    // model occupancy (a cell joins the footprint once the model fills ≥ its threshold, default 4%); do not hand-edit —
    // re-run the script (optionally with a different threshold) and re-paste.
    //   • (X, Y, Z) = cell offset from the placed block. +Z = feed/strike axis; +X = perpendicular; +Y = up.
    //   • Authored as if placed facing SOUTH (= identity); RotateToFacing rotates the WHOLE table for the other 3
    //     facings automatically — so author once for south and place facing south to verify.
    //   • [0] MUST stay (0,0,0) (the master cell). The rest may be in any order.
    //   • "%%" = fraction of the cell the model fills (scan guide; the machine is a thin frame, so a low %% is still
    //     real structure). The cell COUNT is whatever this table holds, NOT a fixed design constant — it grows/shrinks
    //     with the model / threshold.  Re-build + BREAK and RE-PLACE the machine after editing (ghosts are stamped at
    //     placement; an already-placed machine won't pick up table changes).
